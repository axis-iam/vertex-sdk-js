import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { constantName, generatePermissionsTs, generatePermissionsTsFromManifest, type PermissionEntry } from './typescript.js'

describe('generatePermissionsTs', () => {
  const sharedFixture = JSON.parse(readFileSync(new URL('../../../../testdata/permission-manifest-vectors.json', import.meta.url), 'utf8')) as {
    codeGeneration: {
      permissions: PermissionEntry[]
      expectedNames: { typescript: string[] }
      reject: Array<{ name: string; classification: string; permissions: PermissionEntry[] }>
    }
  }
  it('generates valid TypeScript from permissions', () => {
    const result = generatePermissionsTs([
      { resource: 'posts', action: 'read', description: 'Read posts' },
      { resource: 'posts', action: 'write' },
      { resource: 'users', action: 'manage' },
    ])

    expect(result).toContain('// @generated by @axis-iam/vertex-codegen')
    expect(result).toContain("import { permKey, type PermissionKey } from '@axis-iam/vertex'")
    expect(result).toContain('POSTS_READ: permKey("posts", "read")')
    expect(result).toContain('POSTS_WRITE: permKey("posts", "write")')
    expect(result).toContain('USERS_MANAGE: permKey("users", "manage")')
    expect(result).toContain('as const satisfies Record<string, PermissionKey>')
  })

  it('uses custom const name', () => {
    const result = generatePermissionsTs(
      [{ resource: 'orders', action: 'read' }],
      'OrderPerms',
    )
    expect(result).toContain('export const OrderPerms = {')
    expect(result).toContain('export type OrderPermsKey = typeof OrderPerms')
  })

  it('handles empty permissions', () => {
    const result = generatePermissionsTs([])
    expect(result).toContain('export const AppPermissions = {')
    expect(result).toContain('} as const')
  })

  it('sorts manifest entries and escapes wire values deterministically', () => {
    const manifest = { permissions: [
      { resource: 'orders', action: 'read', displayName: 'Read orders' },
      { resource: 'billing-events', action: 'view_detail', description: 'quoted " value' },
    ] }
    const first = generatePermissionsTsFromManifest(manifest)
    const second = generatePermissionsTsFromManifest({ permissions: [...manifest.permissions].reverse() })
    expect(first).toBe(second)
    expect(first.indexOf('BILLING_EVENTS_VIEW_DETAIL')).toBeLessThan(first.indexOf('ORDERS_READ'))
  })

  it('executes every shared rejection vector', () => {
    for (const vector of sharedFixture.codeGeneration.reject) {
      let classification = 'NONE'
      try {
        generatePermissionsTs(vector.permissions)
      } catch (error) {
        classification = classifyCodegenError(error, vector.permissions)
      }
      expect(classification, vector.name).toBe(vector.classification)
    }
  })

  it('uses the frozen identifier mapping', () => {
    expect(constantName('billing-events', 'view_detail')).toBe('BILLING_EVENTS_VIEW_DETAIL')
  })

  it('consumes the shared code-generation vector', () => {
    const source = generatePermissionsTs(sharedFixture.codeGeneration.permissions)
    const names = [...source.matchAll(/^  ([A-Z0-9_]+): permKey/gm)].map((match) => match[1])
    expect(names).toEqual(sharedFixture.codeGeneration.expectedNames.typescript)
  })
})

function classifyCodegenError(error: unknown, permissions: PermissionEntry[]): string {
  const message = error instanceof Error ? error.message : String(error)
  if (message.includes('duplicate permission key')) return 'DUPLICATE_KEY'
  if (message.includes('NFC')) return 'NON_NFC'
  if (message.includes('name collision')) return 'NAME_COLLISION'
  if (permissions.some(permission => permission.resource === '*' || permission.action === '*')) return 'WILDCARD_KEY'
  if (message.includes('concrete lowercase segment')) return 'MALFORMED_KEY'
  return 'UNKNOWN'
}
