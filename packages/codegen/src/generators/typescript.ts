export interface PermissionEntry {
  resource: string
  action: string
  displayName?: string
  name?: string
  description?: string | null
}

export interface PermissionManifestInput {
  permissions: readonly PermissionEntry[]
}

const SEGMENT = /^[a-z0-9_-]{1,128}$/

/**
 * Generate a TypeScript file with permission constants.
 */
export function generatePermissionsTs(
  permissions: readonly PermissionEntry[],
  constName = 'AppPermissions',
): string {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(constName)) throw new TypeError('constName must be a valid TypeScript identifier')
  const entries = prepareEntries(permissions)
  const lines: string[] = [
    '// @generated by @axis-iam/vertex-codegen. Do not edit.',
    "import { permKey, type PermissionKey } from '@axis-iam/vertex';",
    '',
    `export const ${constName} = {`,
  ]

  for (const entry of entries) {
    lines.push(`  ${entry.name}: permKey(${JSON.stringify(entry.permission.resource)}, ${JSON.stringify(entry.permission.action)}),`)
  }

  lines.push(`} as const satisfies Record<string, PermissionKey>;`)
  lines.push('')
  lines.push(`export type ${constName}Key = typeof ${constName}[keyof typeof ${constName}];`)
  lines.push('')

  return lines.join('\n')
}

/** Generate browser-safe typed constants from one explicit structured manifest. */
export function generatePermissionsTsFromManifest(
  manifest: PermissionManifestInput,
  constName = 'AppPermissions',
): string {
  if (!manifest || !Array.isArray(manifest.permissions)) throw new TypeError('manifest permissions must be an array')
  return generatePermissionsTs(manifest.permissions, constName)
}

function prepareEntries(permissions: readonly PermissionEntry[]) {
  const sorted = [...permissions].sort((left, right) => wireKey(left) < wireKey(right) ? -1 : wireKey(left) > wireKey(right) ? 1 : 0)
  const keys = new Set<string>()
  const names = new Map<string, string>()
  return sorted.map((permission) => {
    validateSegment(permission.resource, 'resource')
    validateSegment(permission.action, 'action')
    for (const value of [permission.name, permission.displayName, permission.description]) {
      if (value != null && value.normalize('NFC') !== value) throw new TypeError('permission manifest strings must already be NFC')
    }
    const key = wireKey(permission)
    if (keys.has(key)) throw new TypeError(`duplicate permission key: ${key}`)
    keys.add(key)
    const name = constantName(permission.resource, permission.action)
    const previous = names.get(name)
    if (previous !== undefined) throw new TypeError(`generated permission name collision: ${previous} and ${key} both map to ${name}`)
    names.set(name, key)
    return { name, permission }
  })
}

function validateSegment(value: string, field: string): void {
  if (!SEGMENT.test(value) || value === '*') throw new TypeError(`permission ${field} must be a concrete lowercase segment`)
}

function wireKey(permission: PermissionEntry): string {
  return `${permission.resource}:${permission.action}`
}

export function constantName(resource: string, action: string): string {
  const name = `${resource}_${action}`.toUpperCase().replace(/[^A-Z0-9]+/g, '_')
  return /^[0-9]/.test(name) ? `P_${name}` : name
}
