import { expect, it, vi } from 'vitest'
import { InvitationError } from '@axis-iam/vertex'
import { InvitationJourneyStore } from './invitation-journey-store'
import { invitationApi, invitationProof, invitationRef, invitationView, invitationEnrollment } from './invitation-fixtures.test-support'

it.each(['authenticated', 'registration'] as const)('retries read-only preparation loss explicitly in %s mode before submitting one exchange', async mode => {
  const api = invitationApi(), store = new InvitationJourneyStore(api, { continuation: invitationProof })
  api.prepareEntry.mockRejectedValueOnce(new InvitationError('INVITATION_RESULT_UNKNOWN'))
  await expect(store.open(mode)).rejects.toMatchObject({ code: 'INVITATION_RESULT_UNKNOWN' })
  expect(store.getSnapshot()).toMatchObject({ phase: 'error', journey: null, entryPending: true, unknownAction: null })
  expect(store.hasRef()).toBe(false)
  expect(store.hasContinuation()).toBe(true)
  expect(store.canRetryPreparation()).toBe(true)
  expect(api.exchange).not.toHaveBeenCalled()
  expect(api.registrationContext).not.toHaveBeenCalled()
  expect(api.confirm).not.toHaveBeenCalled()
  await expect(store.confirm()).rejects.toMatchObject({ code: 'INVITATION_REFRESH_REQUIRED' })
  await Promise.all([store.retryPreparation(), store.retryPreparation()])
  expect(api.prepareEntry).toHaveBeenCalledTimes(2)
  expect(api.prepareEntry).toHaveBeenNthCalledWith(2, invitationProof, mode)
  expect(mode === 'authenticated' ? api.exchange : api.registrationContext).toHaveBeenCalledTimes(1)
  expect(mode === 'authenticated' ? api.registrationContext : api.exchange).not.toHaveBeenCalled()
  expect(store.canRetryPreparation()).toBe(false)
  expect(api.confirm).not.toHaveBeenCalled()
  if (mode === 'registration') {
    await expect(store.confirm()).rejects.toMatchObject({ code: 'INVITATION_CONFIRMATION_REQUIRED' })
    await store.register({ identifier: { kind: 'EMAIL', value: 'member@example.test' }, password: 'task-only-password' })
    await store.verifyRegistration('123456')
    expect(api.confirm).not.toHaveBeenCalled()
  }
  await store.confirm()
  expect(api.confirm).toHaveBeenCalledTimes(1)
})
