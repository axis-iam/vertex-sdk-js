import { join } from 'node:path'

/** Only SDK09-11 changed paths; the existing lifecycle suite remains a separate selector. */
export async function runActionsScenario({ mount, click, state, checkLayout, checkContrast, assert, fixture, output }) {
  const capture = async (page, name) => {
    await page.mouse.move(0, 0)
    await page.screenshot({
      path: join(output, `${name}.png`), fullPage: true,
      mask: [page.locator('.axis-security-setup svg,.axis-security-setup code,.axis-security-codes,input')],
    })
  }
  const revealFooter = async (page, label) => {
    await page.locator('.axis-security-footer').scrollIntoViewIfNeeded()
    await page.waitForFunction(() => {
      const footer = document.querySelector('.axis-security-footer').getBoundingClientRect()
      const container = document.querySelector('.axis-ac-layout').getBoundingClientRect()
      return footer.top >= container.top && footer.bottom <= Math.min(container.bottom, innerHeight)
    })
    assert(await page.getByRole('button', { name: /^(Confirm setup|确认启用)$/, exact: true }).isEnabled(), `${label}: the primary setup action is enabled and reachable in the scroll container`)
  }
  const oneConfirmation = async page => {
    await page.getByRole('button', { name: 'Keep setting up', exact: true }).waitFor()
    assert(await page.getByRole('button', { name: 'Confirm cancellation', exact: true }).count() === 1 &&
      await page.getByRole('button', { name: 'Keep setting up', exact: true }).count() === 1, 'SDK10: exactly one pair owns cancellation')
    assert(await page.getByRole('button', { name: 'Confirm setup', exact: true }).count() === 0, 'SDK10: primary setup action is absent during cancellation confirmation')
    assert(await page.getByRole('button', { name: 'Keep setting up', exact: true }).evaluate(node => node === document.activeElement), 'SDK10: cancellation focuses the safe continuation action')
  }
  for (const mode of ['oauth_tokens', 'server_session']) {
    const methods = await mount(mode, 'methods', { longProvider: true })
    const { page } = methods
    await click(page, 'Open account security')
    await page.getByRole('heading', { name: 'Login methods', exact: true }).waitFor()
    await page.locator('.axis-identity-additions .axis-identity-addition-row').first().waitFor()
    assert(await page.locator('.axis-identity-additions .axis-identity-addition-row').count() === 3, `${mode}: additions use three aligned rows`)
    const phone = page.getByRole('button', { name: 'Add phone number', exact: true })
    assert(await phone.isDisabled() && Boolean(await phone.getAttribute('aria-describedby')), `${mode}: server capability denial retains its accessible reason`)
    await page.getByText('Connect a provider', { exact: true }).click()
    const unavailable = page.locator('.axis-identity-provider-additions .axis-identity-addition-row').last()
    assert(await unavailable.getByRole('button', { name: 'Connect', exact: true }).isDisabled(), `${mode}: unavailable provider remains explicitly disabled`)
    await unavailable.getByText('This provider is unavailable.', { exact: true }).waitFor()
    if (mode === 'server_session') {
      await page.locator('.axis-identity-provider-additions').scrollIntoViewIfNeeded()
      await checkLayout(page, 'SDK09 additions desktop light EN long provider')
      await checkContrast(page, 'SDK09 additions desktop light EN')
      await capture(page, 'sdk09-methods-desktop-light-en')
      await page.evaluate(() => { window.accountSecurityHarness.theme('dark'); window.accountSecurityHarness.locale('zh-CN') })
      await page.setViewportSize({ width: 390, height: 844 })
      await page.getByText('绑定第三方账号', { exact: true }).waitFor()
      await page.locator('.axis-identity-provider-additions').scrollIntoViewIfNeeded()
      await checkLayout(page, 'SDK09 additions mobile dark zh long provider')
      await checkContrast(page, 'SDK09 additions mobile dark zh')
      await capture(page, 'sdk09-methods-mobile-dark-zh')
      await page.evaluate(() => { window.accountSecurityHarness.theme('system'); window.accountSecurityHarness.locale('en') })
      await page.emulateMedia({ colorScheme: 'light' })
      await page.waitForFunction(() => document.querySelector('.axis-ac-dialog')?.dataset.colorScheme === 'light')
      await page.emulateMedia({ colorScheme: 'dark' })
      await page.waitForFunction(() => document.querySelector('.axis-ac-dialog')?.dataset.colorScheme === 'dark')
      assert(true, 'SDK09: system follows the host media scheme without another palette')
      await page.evaluate(() => window.accountSecurityHarness.theme('light'))
      await page.setViewportSize({ width: 1100, height: 900 })
    }
    const connect = page.locator('.axis-identity-provider-additions .axis-identity-addition-row').first().getByRole('button', { name: 'Connect', exact: true })
    await connect.click()
    await page.getByLabel('Confirm your current password', { exact: true }).fill('isolated-fixture-password')
    await click(page, 'Verify and continue')
    const popupEvent = page.waitForEvent('popup')
    await page.locator('.axis-identity-operation button').filter({ hasText: 'Use Catalog directory label' }).click()
    const popup = await popupEvent
    await popup.waitForURL(url => url.searchParams.get('identity_operation') === 'proof_pending')
    await click(page, 'I completed provider confirmation')
    await page.getByRole('region', { name: 'External account to connect' }).getByText('v***@verified.invalid', { exact: true }).waitFor()
    assert(fixture.requests.filter(request => request.path.includes('/identity-operations/') && request.path.endsWith('/complete')).length === 0, `${mode}: grouped provider action still requires explicit returned-identity confirmation`)
    await click(page, 'Confirm connection')
    await page.getByRole('heading', { name: 'Change completed', exact: true }).waitFor()
    assert(fixture.requests.filter(request => request.path.includes('/identity-operations/') && request.path.endsWith('/complete')).length === 1, `${mode}: provider grouping preserves one real completion request`)
    await methods.context.close()

    const security = await mount(mode, 'center', { applicationIssuer: 'Customer Application / security settings' })
    const p = security.page
    await click(p, 'Open account security'); await click(p, 'Set up authenticator')
    await p.getByRole('button', { name: 'Show setup instructions', exact: true }).waitFor()
    assert(await p.locator('.axis-security-footer').count() === 1 && await p.getByRole('button', { name: 'Show setup instructions' }).count() === 1, `${mode}: READY uses one operation footer`)
    let releaseBegin
    const beginGate = new Promise(resolve => { releaseBegin = resolve })
    await p.route('**/mfa/operations/*/begin', async route => { await beginGate; await route.continue() })
    await click(p, 'Show setup instructions')
    await p.waitForFunction(() => window.accountSecurityHarness.state().pending)
    await click(p, 'Profile'); await p.keyboard.press('Escape')
    assert(await p.locator('.axis-ac-nav button[aria-current=page]').textContent() === 'Security' && await p.getByRole('button', { name: 'Confirm cancellation' }).count() === 0, `${mode}: busy navigation and Escape neither unmount nor confirm`)
    releaseBegin()
    await p.getByText('FIXTUREONLYSETUP', { exact: true }).waitFor()
    await p.getByText('Customer Application / security settings', { exact: true }).waitFor()
    assert(await p.locator('.axis-security-operation form').count() === 1 && await p.locator('.axis-security-operation form .axis-security-footer button').count() === 2, `${mode}: setup fields precede one primary/cancel footer`)
    assert(await p.getByLabel('Verification code', { exact: true }).evaluate(node => node.closest('footer') === null), `${mode}: verification field is outside the footer`)
    await p.getByLabel('Verification code', { exact: true }).fill('123456')
    if (mode === 'server_session') {
      await checkLayout(p, 'SDK10 setup desktop light EN')
      await capture(p, 'sdk10-setup-desktop-light-en-redacted')
      await revealFooter(p, 'SDK10 setup desktop light EN')
      await capture(p, 'sdk10-setup-footer-desktop-light-en-redacted')
      await p.evaluate(() => { window.accountSecurityHarness.theme('dark'); window.accountSecurityHarness.locale('zh-CN') })
      await p.setViewportSize({ width: 390, height: 844 })
      await p.getByRole('button', { name: '确认启用', exact: true }).waitFor()
      await checkLayout(p, 'SDK10 setup mobile dark zh')
      await capture(p, 'sdk10-setup-mobile-dark-zh-redacted')
      await revealFooter(p, 'SDK10 setup mobile dark zh')
      await capture(p, 'sdk10-setup-footer-mobile-dark-zh-redacted')
      await p.evaluate(() => { window.accountSecurityHarness.theme('light'); window.accountSecurityHarness.locale('en') })
      await p.setViewportSize({ width: 1100, height: 900 })
    }
    await click(p, 'Cancel setup'); await oneConfirmation(p)
    await p.keyboard.press('Escape'); await oneConfirmation(p)
    await click(p, 'Keep setting up')
    assert((await state(p)).hasMaterial, `${mode}: keep retains the same setup material`)
    await click(p, 'Profile'); await oneConfirmation(p); await click(p, 'Keep setting up')
    await p.setViewportSize({ width: 390, height: 844 })
    await p.locator('.axis-ac-back').click(); await oneConfirmation(p)
    assert(await p.locator('.axis-ac-menu').count() === 0, `${mode}: mobile menu cannot hide active security work`)
    await checkLayout(p, 'SDK10 cancellation mobile EN')
    if (mode === 'server_session') await capture(p, 'sdk10-cancel-mobile-light-en-redacted')
    await click(p, 'Keep setting up')
    await p.setViewportSize({ width: 1100, height: 900 })
    await click(p, 'Close account center'); await oneConfirmation(p)
    await click(p, 'Confirm cancellation')
    await p.getByRole('dialog').waitFor({ state: 'hidden' })
    assert(fixture.requests.filter(request => request.path.endsWith('/cancel')).length === 1 && !(await state(p)).hasMaterial, `${mode}: definite cancellation completes the stored close exactly once`)
    assert(await p.locator('#consumer-open').evaluate(node => node === document.activeElement), `${mode}: protected close restores host trigger focus`)
    assert(await p.evaluate(() => JSON.stringify({ html: [...document.documentElement.attributes].map(a => [a.name, a.value]), body: [...document.body.attributes].map(a => [a.name, a.value]), background: getComputedStyle(document.body).backgroundColor, font: getComputedStyle(document.body).fontFamily })) === security.hostBoundary, `${mode}: changed paths leave host attributes and typography unchanged`)
    assert(!/FIXTUREONLYSETUP/.test(await p.evaluate(() => [...Object.values(sessionStorage), ...Object.values(localStorage)].join(' '))), `${mode}: setup material is not persisted`)
    await security.context.close()
  }

  const uncertain = await mount('server_session', 'center', { lostCancel: true })
  await click(uncertain.page, 'Open account security'); await click(uncertain.page, 'Set up authenticator')
  await click(uncertain.page, 'Show setup instructions'); await uncertain.page.getByText('FIXTUREONLYSETUP', { exact: true }).waitFor()
  await click(uncertain.page, 'Close account center'); await oneConfirmation(uncertain.page); await click(uncertain.page, 'Confirm cancellation')
  await uncertain.page.getByText('The result is not confirmed. Check this operation before making another change.', { exact: true }).waitFor()
  await uncertain.page.keyboard.press('Escape')
  assert(await uncertain.page.getByRole('dialog').isVisible() && (await state(uncertain.page)).uncertain, 'SDK10: a lost cancellation result never closes the center')
  await click(uncertain.page, 'Check this operation')
  await uncertain.page.getByRole('heading', { name: 'Operation cancelled', exact: true }).waitFor()
  assert(await uncertain.page.getByRole('dialog').isVisible() && fixture.requests.filter(request => request.path.endsWith('/cancel')).length === 1, 'SDK10: status recovery does not replay cancellation or execute the retired exit intent')
  await uncertain.context.close()

  const dialog = await mount('oauth_tokens', 'dialog')
  await click(dialog.page, 'Open account security'); await click(dialog.page, 'Set up authenticator')
  await click(dialog.page, 'Show setup instructions'); await dialog.page.getByText('FIXTUREONLYSETUP', { exact: true }).waitFor()
  await click(dialog.page, 'Cancel setup'); await dialog.page.keyboard.press('Escape'); await oneConfirmation(dialog.page)
  await click(dialog.page, 'Keep setting up'); await dialog.page.keyboard.press('Escape'); await oneConfirmation(dialog.page)
  await click(dialog.page, 'Confirm cancellation'); await dialog.page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert(fixture.requests.filter(request => request.path.endsWith('/cancel')).length === 1, 'SDK10: native Dialog shares the panel confirmation owner')
  assert(await dialog.page.locator('#consumer-open').evaluate(node => node === document.activeElement), 'SDK10: native Dialog restores focus')
  await dialog.context.close()
}
